#!/usr/bin/env python3
"""
num_mems_touchdown.py -- nonlinear touchdown dynamics of the hyperbolic MEMS
equation  w_tt + gam w_t - Delta w = -lam w^{-2}  (q = 2, sigma = 2/3)
with w = 1 on the boundary, w(0) = 1, w_t(0) = 0:
  (i)  d = 1 on (-1,1) and (ii) radial d = 2 on the unit disk, gam = 0 and 1.

Method (see Section "Numerical verification"):
  1. physical space up to a time t1 (w_min(t1) ~ 0.3): CFL-1 leapfrog
     (d = 1, three grids + Richardson extrapolation) resp. CFL-1/2 leapfrog
     for the radial equation (d = 2, data smoothed by an even least-squares
     fit to remove grid-scale noise generated by the focusing of the
     corner singularity at t = 1, r = 0);
  2. light cone of (T, 0): similarity variables tau = -log((T-t)/(T-t1)),
     xi = x/(T-t), psi1 = (T-t)^{-2/3} w, psi2 = (T-t)^{1/3} w_t, Chebyshev
     collocation without boundary condition, DOP853;
  3. T by bisection (T too large: psi1 -> 0 inside the cone; too small:
     psi1 -> infinity);
  4. independent check of the exponent: physical leapfrog continued to
     w_min ~ 0.02 and fitted with T free.
Outputs: figures/num_mems_touchdown.pdf, figures/num_mems_profiles.pdf and a
summary on stdout.  Runtime ~ 2-6 min (4 processes).
"""
import os
import sys
import time
from multiprocessing import Pool

import numpy as np
from scipy.integrate import solve_ivp
from scipy.optimize import least_squares

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from num_common import (Model, lagr, richardson1d, leapfrog1d, leapfrog_rad,  # noqa: E402
                        even_fit, sim1d, simrad, bisect_T)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIG = os.path.join(ROOT, "figures")
CASES = [("1d", 0.5, 0.0), ("1d", 0.5, 1.0), ("2d", 0.8, 0.0), ("2d", 0.8, 1.0)]
NS1, NSR, RTOL = 20, 16, 1e-12


def front_distance(t1):
    """distance from the centre of the singular front issued at t=0 from the
    boundary corner (|x| = 1); fronts move with speed 1 and reflect."""
    s = t1 % 2.0
    return abs(1.0 - s)


def ode_T(lam, gam, w, v):
    """touchdown time of the ODE w'' = -lam/w^2 - gam w' from (w, v)."""
    ev = lambda t, y: y[0] - 1e-6
    ev.terminal = True
    sol = solve_ivp(lambda t, y: [y[1], -lam / y[0] ** 2 - gam * y[1]], (0, 50), [w, v],
                    events=ev, rtol=1e-10, atol=1e-12)
    return sol.t_events[0][0]


def run_case(case):
    geom, lam, gam = case
    t0 = time.time()
    m = Model("mems", lam=lam, q=2, gam=gam)
    c, sig = m.c, m.sig
    out = dict(geom=geom, lam=lam, gam=gam, c=c)
    # --- coarse run to choose t1 ------------------------------------------
    rec = []
    if geom == "1d":
        leapfrog1d(m.F, gam, 2000, record=lambda t, W: rec.append((t, W.min())),
                   stop=lambda W: W.min() < 0.3)
    else:
        leapfrog_rad(m.F, gam, 1000, record=lambda t, W: rec.append((t, W.min())),
                     stop=lambda W: W.min() < 0.3)
    t1 = np.floor(rec[-1][0] / 0.01) * 0.01
    out["t1"] = t1
    # --- accurate data at t1 ---------------------------------------------
    if geom == "1d":
        x, W, V, info = richardson1d(m.F, gam, t1)
        wf = lambda X: lagr(x, W, X)
        vf = lambda X: lagr(x, V, X)
        out["data_err"] = info["dW_rich"]
        w0, v0 = W[len(x) // 2], V[len(x) // 2]
    else:
        R0 = min(0.45, 0.85 * front_distance(t1))
        fits = []
        for M in (4000, 8000):
            r, W, V = leapfrog_rad(m.F, gam, M, d=2, t1=t1)
            fw, rw = even_fit(r, W, R0)
            fv, rv = even_fit(r, V, R0)
            fits.append((fw, fv, rv))
        wf, vf = fits[1][0], fits[1][1]
        rr = np.linspace(0, R0, 200)
        out["data_err"] = np.max(abs(fits[1][0](rr) - fits[0][0](rr)))
        out["data_err_v"] = np.max(abs(fits[1][1](rr) - fits[0][1](rr)))
        out["noise_v"] = fits[1][2]
        out["R0"] = R0
        w0, v0 = float(wf(np.array([0.0]))[0]), float(vf(np.array([0.0]))[0])
    out["front"] = front_distance(t1)
    Test = t1 + ode_T(lam, gam, w0, v0)

    def run(T, dense=False, Ns=None, fwv=(wf, vf)):
        if geom == "1d":
            return sim1d(m, fwv[0], fwv[1], T, t1, 0.0, Ns=Ns or NS1, rtol=RTOL, dense=dense)
        return simrad(m, fwv[0], fwv[1], T, t1, d=2, Ns=Ns or NSR, rtol=RTOL, dense=dense)

    dT = Test - t1
    lo, hi = t1 + 0.6 * dT, t1 + 1.4 * dT
    lo, hi = bisect_T(run, lo, hi)
    out["T"] = 0.5 * (lo + hi)
    out["Test_ode"] = Test
    assert out["T"] - t1 < out["front"], "cone meets the corner singularity"
    if geom == "2d":   # sensitivity of T to the data (coarser grid)
        lo2, hi2 = bisect_T(lambda T: run(T, fwv=(fits[0][0], fits[0][1])), lo - 1e-4, hi + 1e-4)
        out["T_coarse"] = 0.5 * (lo2 + hi2)
    # resolution check of T (other Ns)
    lo3, hi3 = bisect_T(lambda T: run(T, Ns=(NS1 if geom == "1d" else NSR) + 4),
                        lo - 1e-7, hi + 1e-7)
    out["T_Ns"] = 0.5 * (lo3 + hi3)
    # --- dense trajectories with T = lo and T = hi ------------------------
    trajs = []
    for T in (lo, hi):
        f, sol, grid = run(T, dense=True)
        trajs.append((T, sol))
    taus = np.linspace(0, min(trajs[0][1].t[-1], trajs[1][1].t[-1]), 1200)
    n = len(grid)
    i0 = n // 2 if geom == "1d" else n - 1   # xi = 0 (1d)  /  z = 0 (2d, last node)
    D = {}
    for k, (T, sol) in enumerate(trajs):
        Y = sol.sol(taus)
        P1 = Y[:n]
        D[k] = dict(dev=np.max(abs(P1 - c), axis=0), dev0=P1[i0] - c, d20=Y[n + i0] + sig * c,
                    spat=P1.max(axis=0) - P1.min(axis=0), wmin=P1.min(axis=0),
                    dev2=np.max(abs(Y[n:] + sig * c), axis=0))
    # window where both trajectories agree (unstable mode negligible)
    agree = abs(D[0]["dev0"] - D[1]["dev0"]) < 1e-3 * abs(D[0]["dev0"])
    jmax = np.argmin(agree) if not agree.all() else len(taus)
    jmax = max(jmax, 10)
    out["tau_valid"] = taus[jmax - 1]
    dev0 = 0.5 * (D[0]["dev0"] + D[1]["dev0"])
    sel = slice(0, jmax)
    out["taus"], out["dev"], out["spat"], out["dev0"] = taus[sel], D[0]["dev"][sel], D[0]["spat"][sel], dev0[sel]
    out["dev2"] = D[0]["dev2"][sel]
    out["ratio21"] = D[0]["d20"][jmax - 1] / D[0]["dev0"][jmax - 1]
    out["Tm"] = out["T"] - t1
    out["wmin_sim"] = (out["Tm"] * np.exp(-taus[sel])) ** sig * D[0]["wmin"][sel]
    # longer window for w_min itself: the two trajectories differ by < 1e-4 c
    close = abs(D[0]["dev0"] - D[1]["dev0"]) < 1e-4 * c
    jext = np.argmin(close) if not close.all() else len(taus)
    out["taus_ext"] = taus[:jext]
    out["wmin_ext"] = (out["Tm"] * np.exp(-taus[:jext])) ** sig * D[0]["wmin"][:jext]
    # --- rate fits ----------------------------------------------------------
    tt = taus[sel]
    win = (tt > 3) & (abs(dev0[sel]) > 1e-12)
    if win.sum() > 20:
        def resid(p):
            A, om, B = p
            return (A * np.exp(-om * tt[win]) + B * np.exp(-tt[win]) - dev0[sel][win]) / abs(dev0[sel][win])
        p = least_squares(resid, [dev0[sel][win][0] * np.exp(2 * tt[win][0] / 3), 0.6, 0.0]).x
        out["omega_fit2"] = p[1]
        out["A_fit"] = p[0]
        W0 = c + dev0[sel][win]

        def resid4(p):   # c free: W(tau,0) = Cinf + A e^{-omega tau} + B e^{-tau}
            Ci, A, om, B = p
            return (Ci + A * np.exp(-om * tt[win]) + B * np.exp(-tt[win]) - W0) / abs(W0 - c)
        p4 = least_squares(resid4, [c, p[0], p[1], p[2]]).x
        out["Cinf"], out["omega_fit4"] = p4[0], p4[2]
        late = win & (tt > 0.5 * tt[win].max())
        out["omega_late"] = -np.polyfit(tt[late], np.log(abs(dev0[sel][late])), 1)[0]
        sw = (tt > 3) & (D[0]["spat"][sel] > 1e-11)
        out["omega_spat"] = -np.polyfit(tt[sw], np.log(D[0]["spat"][sel][sw]), 1)[0]
    # --- physical-space continuation for the exponent fit -------------------
    rec = []
    if geom == "1d":
        leapfrog1d(m.F, gam, 16000, record=lambda t, W: rec.append((t, W.min())),
                   stop=lambda W: W.min() < 0.02)
    else:
        leapfrog_rad(m.F, gam, 8000, d=2, record=lambda t, W: rec.append((t, W.min())),
                     stop=lambda W: W.min() < 0.03)
    rec = np.array(rec[::5])
    out["fd_t"], out["fd_w"] = rec[:, 0], rec[:, 1]
    sel = (rec[:, 1] < 0.25) & (rec[:, 1] > 0.0)
    tf, wfit = rec[sel, 0], rec[sel, 1]

    def r3(p):
        T, C, b = p
        return np.log(C) + b * np.log(np.maximum(T - tf, 1e-14)) - np.log(wfit)

    def r4(p):
        T, C, b, e = p
        s = np.maximum(T - tf, 1e-14)
        return np.log(C) + b * np.log(s) + np.log(1 + e * s ** (2 / 3)) - np.log(wfit)

    p3 = least_squares(r3, [tf[-1] + 1e-3, c, 0.66]).x
    p4 = least_squares(r4, [p3[0], c, 0.66, 0.0]).x
    out["fit3"], out["fit4"] = p3, p4
    out["fit_window"] = (wfit.min(), wfit.max())
    out["time"] = time.time() - t0
    return out


def main():
    t0 = time.time()
    with Pool(4) as pool:
        res = pool.map(run_case, CASES, chunksize=1)
    print("hyperbolic MEMS, q = 2, sigma = 2/3, c = (9 lam/2)^(1/3)")
    for o in res:
        print("\n--- %s lam=%.2f gam=%.0f   c=%.10f  (case time %.0f s)" % (o["geom"], o["lam"], o["gam"], o["c"], o["time"]))
        print("  t1 = %.2f, data error estimate %.1e%s, singular front at |x| = %.2f, cone radius T-t1 = %.3f"
              % (o["t1"], o["data_err"], "" if o["geom"] == "1d" else
                 " (w_t: %.1e, grid noise in w_t %.1e, fit radius %.2f)" % (o["data_err_v"], o["noise_v"], o["R0"]),
                 o["front"], o["Tm"]))
        print("  T (bisection) = %.15f ; with Ns+4: %.15f ; local-ODE estimate from t1: %.6f"
              % (o["T"], o["T_Ns"], o["Test_ode"]) + ("" if o["geom"] == "1d" else
                                                      " ; with coarser data: %.12f" % o["T_coarse"]))
        print("  valid tau window [0, %.1f]  (T - t down to %.1e)" % (o["tau_valid"], o["Tm"] * np.exp(-o["tau_valid"])))
        print("  W(tau,0) - c at end of window: %.2e ; max|W - c| %.2e ; spatial variation %.2e"
              % (o["dev0"][-1], o["dev"][-1], o["spat"][-1]))
        if "omega_fit2" in o:
            print("  omega: fit A e^{-omega tau} + B e^{-tau}: %.5f ; late-window slope: %.5f ; "
                  "spatial variation rate: %.4f" % (o["omega_fit2"], o["omega_late"], o["omega_spat"]))
            print("  leading coefficient: W - c ~ A (T-t)^{2/3}, A = %.4f (A/c = %.4f)" % (o["A_fit"] * o["Tm"] ** (-2 / 3), o["A_fit"] * o["Tm"] ** (-2 / 3) / o["c"]))
            print("  fit with c free: W(tau,0) = C + A e^{-omega tau} + B e^{-tau}: C = %.10f (C/c - 1 = %.1e), omega = %.5f"
                  % (o["Cinf"], o["Cinf"] / o["c"] - 1, o["omega_fit4"]))
            print("  (psi2(0) + 2c/3)/(psi1(0) - c) at end of window: %.4f  (gap eigenfunction (1, -4/3): -4/3)" % o["ratio21"])
        print("  physical-space fit on w_min in [%.3f, %.3f]:" % o["fit_window"])
        print("    w = C (T-t)^beta              : T=%.6f C=%.5f beta=%.5f" % tuple(o["fit3"]))
        print("    w = C (T-t)^beta (1+e (T-t)^{2/3}): T=%.6f C=%.5f beta=%.5f e=%.3f" % tuple(o["fit4"]))
        se = o["Tm"] * np.exp(-o["taus_ext"][-1])
        print("  similarity data: w_min/(T-t)^{2/3} at T-t = %.1e : %.10f (c = %.10f)"
              % (se, o["wmin_ext"][-1] / se ** (2 / 3), o["c"]))
        lw, ls_ = np.log(o["wmin_ext"]), np.log(o["Tm"]) - o["taus_ext"]
        k = (ls_ < np.log(1e-6))
        if k.sum() > 5:
            print("  slope of log w_min vs log(T-t) for T-t < 1e-6 (T from bisection): %.8f" % np.polyfit(ls_[k], lw[k], 1)[0])
    make_figures(res)
    print("\ntotal time %.0f s" % (time.time() - t0))


def make_figures(res):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 9})
    cols = ["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728"]
    lab = lambda o: r"$d=%s$, $\lambda=%.1f$, $\gamma=%d$" % (o["geom"][0], o["lam"], o["gam"])
    fig, axs = plt.subplots(1, 3, figsize=(11, 3.5))
    for o, col in zip(res, cols):
        s_fd = o["T"] - o["fd_t"]
        m = s_fd > 0
        s_sim = o["Tm"] * np.exp(-o["taus"])
        s_ext = o["Tm"] * np.exp(-o["taus_ext"])
        axs[0].loglog(s_fd[m], o["fd_w"][m], "-", color=col, lw=0.8, alpha=0.6)
        axs[0].loglog(s_ext, o["wmin_ext"], "-", color=col, lw=1.6, label=lab(o))
        axs[1].semilogx(s_fd[m], o["fd_w"][m] / s_fd[m] ** (2 / 3) / o["c"], "-", color=col, lw=0.8, alpha=0.6)
        axs[1].semilogx(s_ext, o["wmin_ext"] / s_ext ** (2 / 3) / o["c"], "-", color=col, lw=1.6)
        axs[2].loglog(s_sim, o["dev"], "-", color=col, lw=1.5)
        axs[2].loglog(s_sim, o["spat"], "--", color=col, lw=1.0)
    ss = np.logspace(-11, -0.5, 10)
    axs[0].loglog(ss, 0.3 * ss ** (2 / 3), "k:", lw=1)
    axs[0].text(3e-4, 4e-5, r"$\propto (T-t)^{2/3}$", fontsize=8)
    axs[0].set_xlabel(r"$T-t$")
    axs[0].set_ylabel(r"$\min_x w(t,x)$")
    axs[0].legend(fontsize=7, loc="lower left")
    axs[1].axhline(1, color="k", ls=":", lw=1)
    axs[1].set_xlabel(r"$T-t$")
    axs[1].set_ylabel(r"$w_{\min}/(c\,(T-t)^{2/3})$")
    axs[1].set_ylim(0.6, 1.05)
    axs[2].loglog(ss, 0.2 * ss ** (2 / 3), "k:", lw=1)
    axs[2].loglog(ss, 0.05 * ss, "k-.", lw=1)
    axs[2].text(3e-9, 1.5e-7, r"$(T-t)^{2/3}$", fontsize=8)
    axs[2].text(1e-6, 2e-10, r"$(T-t)^{1}$", fontsize=8)
    axs[2].set_xlabel(r"$T-t$")
    axs[2].set_ylabel(r"$\|W-c\|_\infty$ (solid), $\mathrm{osc}_\xi W$ (dashed)")
    for ax in axs:
        ax.invert_xaxis()
        ax.grid(alpha=0.3, which="both", lw=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "num_mems_touchdown.pdf"))
    plt.close(fig)
    print("wrote figures/num_mems_touchdown.pdf")

    # light-cone profiles (1d, gam=0) and local exponent
    fig, axs = plt.subplots(1, 2, figsize=(8.5, 3.3))
    o = res[0]
    m = Model("mems", lam=o["lam"], q=2, gam=o["gam"])
    t1 = o["t1"]
    x, W, V, _ = richardson1d(m.F, o["gam"], t1)
    f, sol, xi = sim1d(m, lambda X: lagr(x, W, X), lambda X: lagr(x, V, X), o["T"], t1, 0.0,
                       Ns=NS1, rtol=RTOL, dense=True)
    xx = np.linspace(-1, 1, 201)
    from numpy.polynomial import chebyshev as Ch
    for tau in [0, 1, 2, 4, 8, 16]:
        if tau > sol.t[-1]:
            continue
        P1 = sol.sol(tau)[: len(xi)]
        cf = Ch.chebfit(xi, P1, len(xi) - 1)
        axs[0].plot(xx, Ch.chebval(xx, cf), label=r"$T-t=%.1e$" % (o["Tm"] * np.exp(-tau)))
    axs[0].axhline(o["c"], color="k", ls=":", lw=1)
    axs[0].set_xlabel(r"$\xi=x/(T-t)$")
    axs[0].set_ylabel(r"$W=(T-t)^{-2/3}w$")
    axs[0].set_title(r"$d=1$, $\lambda=0.5$, $\gamma=0$: light-cone profile", fontsize=9)
    axs[0].legend(fontsize=7)
    for o, col in zip(res, cols):
        s = o["Tm"] * np.exp(-o["taus_ext"])
        lw = np.log(o["wmin_ext"])
        slope = np.gradient(lw, np.log(s))
        axs[1].semilogx(s, slope, color=col, label=lab(o))
    axs[1].axhline(2 / 3, color="k", ls=":", lw=1)
    axs[1].set_ylim(0.3, 0.75)
    axs[1].invert_xaxis()
    axs[1].set_xlabel(r"$T-t$")
    axs[1].set_ylabel(r"$d\log w_{\min}/d\log(T-t)$")
    axs[1].legend(fontsize=7)
    axs[1].grid(alpha=0.3, which="both", lw=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "num_mems_profiles.pdf"))
    plt.close(fig)
    print("wrote figures/num_mems_profiles.pdf")


if __name__ == "__main__":
    main()
